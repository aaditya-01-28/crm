import { PrismaClient } from "@prisma/client";
import bcrypt from "bcryptjs";

const BASE_URL = "http://localhost:3000";

async function runTests() {
  console.log("==================================================");
  console.log("🧪 TESTING PASSWORD POLICY & RESET FLOW");
  console.log("==================================================");

  // --- Test 1: Level 1 Sales Rep (rep1@textorasms.com) forgot password ---
  console.log("\n[Test 1] Testing Level 1 (Sales Rep) Forgot Password...");
  const repRes = await fetch(`${BASE_URL}/api/auth/forgot-password`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      email: "rep1@textorasms.com",
      notes: "Forgot my login password, need urgent reset.",
    }),
  });

  const repData = await repRes.json();
  console.log("Response:", repRes.status, repData);

  if (repRes.status !== 200 || !repData.isRequestRaised || repData.requesterRole !== "sales_rep") {
    throw new Error("Test 1 Failed: Expected isRequestRaised: true for Level 1 user");
  }
  console.log("✅ Test 1 Passed: Level 1 cannot reset own password; request raised for Super Admin.");

  // --- Test 2: Level 2 Sales Manager (manager@textorasms.com) forgot password ---
  console.log("\n[Test 2] Testing Level 2 (Sales Manager) Forgot Password...");
  const mgrRes = await fetch(`${BASE_URL}/api/auth/forgot-password`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      email: "manager@textorasms.com",
      notes: "Manager password reset requested.",
    }),
  });

  const mgrData = await mgrRes.json();
  console.log("Response:", mgrRes.status, mgrData);

  if (mgrRes.status !== 200 || !mgrData.isRequestRaised || mgrData.requesterRole !== "sales_manager") {
    throw new Error("Test 2 Failed: Expected isRequestRaised: true for Level 2 user");
  }
  console.log("✅ Test 2 Passed: Level 2 cannot reset own password; request raised for Super Admin.");

  // --- Test 3: Level 3 Super Admin (aaditya@textorasms.com) forgot password ---
  console.log("\n[Test 3] Testing Level 3 (Super Admin) Forgot Password...");
  const adminRes = await fetch(`${BASE_URL}/api/auth/forgot-password`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      email: "aaditya@textorasms.com",
    }),
  });

  const adminData = await adminRes.json();
  console.log("Response:", adminRes.status, adminData);

  if (adminRes.status !== 200 || !adminData.isSuperAdmin) {
    throw new Error("Test 3 Failed: Expected isSuperAdmin: true for Level 3 Super Admin");
  }
  console.log("✅ Test 3 Passed: Level 3 Super Admin can perform self-service email reset.");

  // --- Test 4: Super Admin Login & View Password Requests ---
  console.log("\n[Test 4] Super Admin login & inspect requests...");
  const loginRes = await fetch(`${BASE_URL}/api/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      email: "aaditya@textorasms.com",
      password: "Admin@1234",
    }),
  });

  const loginData = await loginRes.json();
  if (!loginRes.ok || !loginData.accessToken) {
    throw new Error(`Admin login failed: ${JSON.stringify(loginData)}`);
  }
  const adminToken = loginData.accessToken;
  console.log("✅ Admin logged in successfully.");

  const requestsRes = await fetch(`${BASE_URL}/api/team/password-requests`, {
    headers: {
      Authorization: `Bearer ${adminToken}`,
      Cookie: `token=${adminToken}`,
    },
  });

  const requestsData = await requestsRes.json();
  console.log("Pending requests count:", requestsData.pendingCount);
  console.log("Requests received:", requestsData.requests?.map((r: any) => ({
    id: r.id,
    user: r.email,
    role: r.role,
    status: r.status,
    notes: r.userNotes,
  })));

  const rep1Request = requestsData.requests?.find((r: any) => r.email === "rep1@textorasms.com" && r.status === "pending");
  if (!rep1Request) {
    throw new Error("Test 4 Failed: Expected to find pending reset request for rep1@textorasms.com");
  }
  console.log("✅ Test 4 Passed: Super Admin can view all pending password reset requests.");

  // --- Test 5: Super Admin resolves rep1 request with new password ---
  console.log("\n[Test 5] Super Admin resolving request with new password...");
  const newTempPass = "Rep1NewPass@2026!";
  const resolveRes = await fetch(`${BASE_URL}/api/team/password-requests`, {
    method: "PATCH",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${adminToken}`,
      Cookie: `token=${adminToken}`,
    },
    body: JSON.stringify({
      requestId: rep1Request.id,
      action: "resolve",
      newPassword: newTempPass,
      adminNotes: "Temporary password generated by Super Admin.",
    }),
  });

  const resolveData = await resolveRes.json();
  console.log("Resolve response:", resolveRes.status, resolveData);
  if (!resolveRes.ok || !resolveData.success) {
    throw new Error("Test 5 Failed: Could not resolve password request");
  }
  console.log("✅ Test 5 Passed: Super Admin successfully reset password and resolved request.");

  // --- Test 6: Verify Rep1 can login with the newly set password ---
  console.log("\n[Test 6] Testing Login as Rep 1 with new password...");
  const repLoginRes = await fetch(`${BASE_URL}/api/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      email: "rep1@textorasms.com",
      password: newTempPass,
    }),
  });

  const repLoginData = await repLoginRes.json();
  console.log("Rep1 login response:", repLoginRes.status, repLoginData.user?.email);
  if (!repLoginRes.ok || !repLoginData.accessToken) {
    throw new Error("Test 6 Failed: Rep1 failed to login with new password");
  }
  console.log("✅ Test 6 Passed: Rep1 successfully authenticated with Super-Admin-assigned password.");

  // --- Test 7: Verify Rep1 old password is now rejected ---
  console.log("\n[Test 7] Testing Rep 1 old password rejection...");
  const oldLoginRes = await fetch(`${BASE_URL}/api/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      email: "rep1@textorasms.com",
      password: "Rep@1234",
    }),
  });
  console.log("Old password login response:", oldLoginRes.status);
  if (oldLoginRes.status === 200) {
    throw new Error("Test 7 Failed: Old password should have been rejected!");
  }
  console.log("✅ Test 7 Passed: Old password correctly rejected.");

  // --- Test 8: Non-Super Admin cannot access /api/team/password-requests ---
  console.log("\n[Test 8] Testing RBAC guard: Rep 1 cannot access /api/team/password-requests...");
  const repToken = repLoginData.accessToken;
  const unauthorizedRes = await fetch(`${BASE_URL}/api/team/password-requests`, {
    headers: {
      Authorization: `Bearer ${repToken}`,
      Cookie: `token=${repToken}`,
    },
  });
  console.log("Unauthorized request status:", unauthorizedRes.status);
  if (unauthorizedRes.status !== 403) {
    throw new Error("Test 8 Failed: Expected 403 Forbidden for non-super_admin");
  }
  console.log("✅ Test 8 Passed: Non-Super Admin blocked from password requests management endpoint.");

  // --- Cleanup: Reset rep1 password back to standard Rep@1234 for dev consistency ---
  console.log("\n[Cleanup] Restoring rep1 password to Rep@1234...");
  const restoreRes = await fetch(`${BASE_URL}/api/team/${rep1Request.userId}`, {
    method: "PATCH",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${adminToken}`,
      Cookie: `token=${adminToken}`,
    },
    body: JSON.stringify({
      newPassword: "Rep@1234",
    }),
  });
  const restoreData = await restoreRes.json();
  console.log("Restore response:", restoreRes.status, restoreData.success);

  console.log("\n==================================================");
  console.log("🎉 ALL TESTS PASSED SUCCESSFULLY!");
  console.log("==================================================");
}

runTests().catch((err) => {
  console.error("❌ TEST SUITE FAILED:", err);
  process.exit(1);
});
